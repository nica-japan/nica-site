def ext(url, label, kind="外部サイト"):
    """外部サイトへのリンク。読み上げでリンク先が分かる文言にする。"""
    return f'<a href="{url}">{label}<span class="ext">（{kind}）</span></a>'


def yt(vid, label):
    return ext(f"https://youtu.be/{vid}", label, "YouTube")


_MANIFEST = json.loads(
    (Path(__file__).parent / "assets" / "img" / "manifest.json")
    .read_text(encoding="utf-8")
)


def img(name, alt, caption, base="../"):
    """写真・図版。WebP を優先し、寸法を入れて表示のガタつきを防ぐ。"""
    m = _MANIFEST[name]
    return (
        "<figure>\n"
        "  <picture>\n"
        f'    <source srcset="{base}assets/img/{m["webp"]}" type="image/webp">\n'
        f'    <img src="{base}assets/img/{m["jpg"]}" alt="{alt}"\n'
        f'         width="{m["width"]}" height="{m["height"]}"\n'
        '         loading="lazy" decoding="async">\n'
        "  </picture>\n"
        f"  <figcaption>{caption}</figcaption>\n"
        "</figure>"
    )


def video(vid, thumb, caption, label, base="../../"):
    """動画。開くまで YouTube へ通信しないよう details で包む。

    サムネイルは自前で持っているので、閉じている間は外部への通信が
    まったく発生しない。JavaScript も使わない。
    """
    m = _MANIFEST[thumb]
    return (
        '<figure class="video-figure">\n'
        "  <details>\n"
        '    <summary><span class="summary-inner">'
        '<span class="play" aria-hidden="true"></span>'
        "<span>動画を再生する（YouTube を読み込みます）</span>"
        "</span></summary>\n"
        '    <div class="video">\n'
        f'      <iframe src="https://www.youtube-nocookie.com/embed/{vid}"'
        f' title="{label}" loading="lazy"'
        ' allow="accelerometer; clipboard-write; encrypted-media; gyroscope; picture-in-picture"'
        " allowfullscreen></iframe>\n"
        "    </div>\n"
        "  </details>\n"
        '  <picture class="video-thumb">\n'
        f'    <source srcset="{base}assets/img/{m["webp"]}" type="image/webp">\n'
        f'    <img src="{base}assets/img/{m["jpg"]}" alt=""\n'
        f'         width="{m["width"]}" height="{m["height"]}"\n'
        '         loading="lazy" decoding="async">\n'
        "  </picture>\n"
        f'  <figcaption>{caption}　{yt(vid, "この動画を YouTube で見る")}</figcaption>\n'
        "</figure>"
    )


def records(items):
    """[(日付, [段落, ...]), ...] を記録リストにする。"""
    out = ['<ul class="records">']
    for date, paras in items:
        out.append("  <li>")
        out.append(f'    <p class="rec-date">{date}</p>')
        for p in paras:
            out.append(f'    <p class="rec-body">{p}</p>')
        out.append("  </li>")
    out.append("</ul>")
    return "\n".join(out)


def _month_key(date):
    """日付の文字列から、月ごとにまとめるための鍵と見出し文字を作る。

    「2024年11月27日」も「2024年11月〜2025年1月」も 2024年11月 にまとめる。
    """
    m = re.match(r"(\d{4})年\s*(\d{1,2})月", date)
    if m:
        return f"m-{m.group(1)}-{int(m.group(2)):02d}", f"{m.group(1)}年{int(m.group(2))}月"
    m = re.match(r"(\d{1,2})月", date)
    if m:
        return f"m-{int(m.group(1)):02d}", f"{int(m.group(1))}月"
    return "m-" + re.sub(r"[^0-9a-zA-Z]+", "-", date).strip("-"), date


def grouped_records(items, index_from=4):
    """記録を月ごとの見出しでまとめ、必要ならページ内目次を付ける。

    見出しにすることで、読み上げソフトの見出し一覧から目的の月へ飛べる。
    月が index_from 個以上あるときだけ、冒頭に目次を置く。
    """
    groups = []
    for date, paras in items:
        key, label = _month_key(date)
        if groups and groups[-1][0] == key:
            groups[-1][2].append((date, paras))
        else:
            groups.append([key, label, [(date, paras)]])

    out = []
    if len(groups) >= index_from:
        out.append('<nav class="page-index" aria-labelledby="page-index-heading">')
        out.append('  <h2 id="page-index-heading">このページの内容</h2>')
        out.append("  <ul>")
        for key, label, rows in groups:
            n = f"（{len(rows)}件）" if len(rows) > 1 else ""
            out.append(f'    <li><a href="#{key}">{label}{n}</a></li>')
        out.append("  </ul>")
        out.append("</nav>")

    for key, label, rows in groups:
        out.append(f'<h2 id="{key}">{label}</h2>')
        out.append('<ul class="records">')
        for date, paras in rows:
            out.append("  <li>")
            # 「11月27日」のように日付まで分かるものは、見出しと別に残す
            if date != label:
                out.append(f'    <p class="rec-date">{date}</p>')
            for para in paras:
                out.append(f'    <p class="rec-body">{para}</p>')
            out.append("  </li>")
        out.append("</ul>")
    return "\n".join(out)


def cards(items):
    """[(href, 見出し, 説明), ...] を入口リンクのカードにする。"""
    out = ['<ul class="cards">']
    for href, title, desc in items:
        out.append(
            f'  <li><a href="{href}"><span class="card-title">{title}</span>'
            f'<span class="card-desc">{desc}</span></a></li>'
        )
    out.append("</ul>")
    return "\n".join(out)


